SYSTEM_PROMPT = (
    "You are an expert resume writer who specialises in ATS-optimised, "
    "impact-driven resumes for top tech and finance companies. "
    "Return ONLY valid JSON — no markdown, no extra text."
)


def _escape_latex(s: str) -> str:
    """Escape special LaTeX characters."""
    replacements = [
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
        ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
        ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"),
    ]
    for old, new in replacements:
        s = s.replace(old, new)
    return s


