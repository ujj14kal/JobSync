@router.get("/status")
async def resume_builder_status(user_id: str = Depends(get_current_user_id)):
    """
    Returns the user's current resume generation quota.
    Used by the frontend to show the usage meter + correct AI label.
    """
    plan  = await get_user_plan(user_id)
    usage = await get_monthly_usage(user_id)
    used  = usage.get("resume_count", 0)

    if plan == "pro":
        limit = PRO_RESUME_LIMIT
        model = "claude-sonnet"
    else:
        limit = FREE_RESUME_LIMIT
        model = "jobsynk-ai"

    return {
        "plan":            plan,
        "model":           model,
        "uses_used":       used,
        "uses_limit":      limit,
        "uses_remaining":  max(0, limit - used),
        "locked":          used >= limit,
        "requires_pro":    plan == "free" and used >= FREE_RESUME_LIMIT,
    }


@router.post("/generate")
async def generate_resume(
    body: GenerateRequest,
    user_id: str = Depends(get_current_user_id),
):
    """
    Tiered resume generation:
      Free       → JobSynk AI Engine (Groq LLaMA-3.3-70b), limit 2/month
      Credit     → Claude Sonnet, 1 credit per generation (resume_pack purchase)
      Pro        → Claude Sonnet, limit 5/month
    """
    plan  = await get_user_plan(user_id)
    usage = await get_monthly_usage(user_id)
    used  = usage.get("resume_count", 0)

    # ── Check for purchased resume_pack credits (non-Pro) ────────────────────
    using_credit = False
    if plan != "pro":
        sb = get_supabase()
        credit = await asyncio.to_thread(
            lambda: sb.table("user_credits")
            .select("id, credits_remaining")
            .eq("user_id", user_id)
            .eq("credit_type", "resume_pack")
            .gt("credits_remaining", 0)
            .order("created_at")
            .limit(1)
            .execute()
        )
        if credit.data:
            # Consume 1 credit and unlock Claude for this generation
            row = credit.data[0]
            await asyncio.to_thread(
                lambda: sb.table("user_credits")
                .update({"credits_remaining": row["credits_remaining"] - 1})
                .eq("id", row["id"])
                .execute()
            )
            using_credit = True
            plan = "pro"  # treat as Pro for this request
            logger.info("Resume pack credit consumed for user %s (remaining: %d)", user_id, row["credits_remaining"] - 1)

    if plan == "pro":
        if not using_credit and used >= PRO_RESUME_LIMIT:
            raise HTTPException(
                status_code=429,
                detail=f"Monthly limit reached ({PRO_RESUME_LIMIT} resumes/month on Pro). Resets on the 1st.",
            )
    else:
        if used >= FREE_RESUME_LIMIT:
            raise HTTPException(
                status_code=402,
                detail=f"Free limit reached ({FREE_RESUME_LIMIT} resumes/month). Upgrade to Pro for {PRO_RESUME_LIMIT}/month with Claude Sonnet.",
            )

    # ── Build user data dict ─────────────────────────────────────────────────
    raw_data: dict = {}
    raw_text: str = ""

    if body.use_active_resume:
        try:
            sb = get_supabase()
            result = await asyncio.to_thread(
                lambda: sb.table("resumes")
                .select("parsed_data, raw_text")
                .eq("user_id", user_id)
                .eq("is_active", True)
                .limit(1)
                .execute()
            )
            if result.data:
                row = result.data[0]
                raw_data = row.get("parsed_data") or {}
                raw_sections = raw_data.get("raw_sections", {})
                raw_text = "\n\n".join(
                    f"[{k.upper()}]\n{v}" for k, v in raw_sections.items() if v.strip()
                )
        except Exception as e:
            logger.warning("Could not fetch active resume: %s", e)

    if body.use_active_resume:
        user_info = {
            "contact":    raw_data.get("contact", {}),
            "education":  raw_data.get("education", []),
            "experience": raw_data.get("experience", []),
            "projects":   raw_data.get("projects", []),
            "skills":     raw_data.get("skills", []),
            "summary":    raw_data.get("summary", ""),
        }
    else:
        user_info = {
            "contact":    body.contact.model_dump(),
            "education":  [e.model_dump() for e in body.education],
            "experience": [e.model_dump() for e in body.experience],
            "projects":   [p.model_dump() for p in body.projects],
            "skills":     body.skills_raw,
            "activities": body.activities,
            "awards":     body.awards,
        }

    jd_context  = f"\n\nTARGET JOB DESCRIPTION (tailor keywords to this):\n{body.target_job[:1000]}" if body.target_job else ""
    raw_context = f"\n\nFULL RESUME RAW TEXT (use this to find activities, awards, projects the parser may have missed):\n{raw_text[:3000]}" if raw_text else ""

    prompt = f"""You are an elite resume writer for top tech and finance companies. Transform this data into a FULL, page-filling, ATS-optimised resume.{jd_context}{raw_context}

PARSED DATA:
{json.dumps(user_info, indent=2)}

STRICT RULES:
1. EVERY experience bullet starts with a powerful action verb (Built, Engineered, Designed, Led, Reduced, Increased, Launched, Automated, Scaled, Optimised, Implemented, Architected...)
2. Write 5-6 bullets per experience role — be specific, detailed, and add approximate metrics where reasonable
3. Each bullet should be 80-140 characters — substantial and impactful, NOT vague one-liners
4. Generate 2-3 projects from the experience if no explicit projects exist
5. Each project gets 2-3 strong bullets describing what was built and the impact
6. Write a compelling 3-sentence professional summary covering: who they are, what they build, what they're driven by
7. Extract ALL activities (clubs, competitions, sports) from raw text — include all of them
8. Extract ALL awards/achievements from raw text — include all of them
9. Organise skills into exactly these 5 categories: Languages, Frameworks/Libraries, Databases, Tools, Cloud
10. Keep all facts (company names, dates, institutions, GPA) EXACTLY as provided — never invent facts
11. The output must be RICH and COMPREHENSIVE enough to fill a full A4 page

Return ONLY this JSON structure:
{{
  "contact": {{"name":"","email":"","phone":"","location":"","linkedin":"","github":"","portfolio":""}},
  "summary": "3-sentence professional summary",
  "education": [{{"degree":"","institution":"","location":"","start_date":"","end_date":"","gpa":""}}],
  "experience": [{{"title":"","company":"","location":"","start_date":"","end_date":"","bullets":["5-6 detailed bullets each"]}}],
  "projects": [{{"name":"","tech_stack":"comma,separated,stack","url":"","bullets":["2-3 strong bullets"]}}],
  "skills": {{"Languages":["..."],"Frameworks/Libraries":["..."],"Databases":["..."],"Tools":["..."],"Cloud":["..."]}},
  "activities": ["Full activity description with year range"],
  "awards": ["Full award description with year"]
}}"""

    try:
        if plan == "pro":
            # ── Pro: Claude Sonnet ───────────────────────────────────────────
            raw = await claude_complete(
                user_id=user_id,
                feature="resume",
                system=SYSTEM_PROMPT,
                messages=[{"role": "user", "content": prompt}],
                max_tokens=4000,
                skip_quota_check=True,   # already checked above
            )
            model_used = "claude-sonnet"
        else:
            # ── Free: JobSynk AI Engine (Groq) ───────────────────────────────
            raw = await groq_call(
                model=settings.GROQ_MODEL,
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user",   "content": prompt},
                ],
                temperature=0.35,
                max_tokens=4000,
                json_mode=True,
                use_cache=False,
            )
            model_used = "jobsynk-ai"
            # Increment free usage counter (fire-and-forget)
            asyncio.create_task(_increment_resume_count(user_id))

        structured = json.loads(raw)
        latex = _build_latex(structured, template=body.template)

        # Calculate remaining after this generation
        new_used = used + 1
        limit = PRO_RESUME_LIMIT if plan == "pro" else FREE_RESUME_LIMIT

        return {
            "structured":      structured,
            "latex":           latex,
            "model_used":      model_used,
            "template":        body.template,
            "uses_used":       new_used,
            "uses_remaining":  max(0, limit - new_used),
            "uses_limit":      limit,
        }

    except HTTPException:
        raise
    except Exception as e:
        logger.error("Resume generation failed", exc_info=e)
        raise HTTPException(status_code=502, detail="Could not generate resume. Please try again.")
