async def _increment_resume_count(user_id: str) -> None:
    """Atomically increment resume_count in monthly_usage (fire-and-forget)."""
    supabase = get_supabase()
    month = _current_month()
    try:
        await asyncio.to_thread(
            lambda: supabase.rpc("increment_monthly_usage", {
                "p_user_id":     user_id,
                "p_month":       month,
                "p_feature_col": "resume_count",
                "p_tokens":      0,
                "p_cost_inr":    0,
                "p_chat_tokens": 0,
            }).execute()
        )
    except Exception as e:
        logger.warning("Failed to increment resume count: %s", e)


