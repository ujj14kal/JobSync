class ContactInput(BaseModel):
    name: str
    email: str
    phone: str = ""
    location: str = ""
    linkedin: str = ""
    github: str = ""
    portfolio: str = ""

class EducationInput(BaseModel):
    degree: str
    institution: str
    location: str = ""
    start_date: str = ""
    end_date: str = ""
    gpa: str = ""
